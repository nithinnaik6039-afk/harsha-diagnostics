function NavigationSync() {
  const navigation = useNavigation();

  useEffect(() => {
    console.log('[NAV SYNC ROUTE NAMES]', navigation.getState()?.routeNames);
  }, [navigation]);

  useEffect(() => {
    if (Platform.OS === 'web') {
      const handlePopState = () => {
        const path = window.location.pathname;
        console.log('[POPSTATE SYNC DEFERRED]', path);
        setTimeout(() => {
          const separator = path.includes('?') ? '&' : '?';
          router.replace((path + separator + 'pop=' + Date.now()) as any);
        }, 50);
      };
      window.addEventListener('popstate', handlePopState);
      return () => {
        window.removeEventListener('popstate', handlePopState);
      };
    }
  }, [navigation]);

  return null;
}

